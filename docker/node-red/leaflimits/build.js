#!/usr/bin/env node
'use strict';
// Builds ../flows/leaflimits.json (the importable "LeafLimits" tab) from src/*.js.
//   node docker/node-red/leaflimits/build.js
// The unit tests require() this file and run the very same function texts.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
const OUT = path.join(__dirname, '..', 'flows', 'leaflimits.json');
// The existing "Local Mosquitto" config node of the MicroHydros flows. It is referenced by id and not
// included, so the tab reuses the connection the validation flow already has.
const BROKER_ID = process.env.LEAFLIMITS_BROKER_ID || '6fcdce2f11ec0ec3';
const TAB = 'll_tab';

const read = (f) => fs.readFileSync(path.join(SRC, f), 'utf8').replace(/\s+$/, '') + '\n';
const common = read('common.js');
const indent = (s) => s.replace(/\n$/, '').split('\n').map((l) => (l ? '    ' + l : l)).join('\n') + '\n';

const sources = {};   // function node name -> full function text, for the unit tests

function fnText(file, outputs, kind) {
    const body = read(file);
    const failure = kind === 'api'
        ? `    node.error(e, msg);\n    const r = LL.reply(msg, 500, { message: 'Internal error.' });\n    return ${outputs > 1 ? '[null, r]' : 'r'};`
        : '    node.error(e);\n    return ' + (outputs > 0 ? 'null' : '') + ';';
    return `// Generated by docker/node-red/leaflimits/build.js from src/common.js and src/${file}. Edit the source files, not this text.\n` +
        `${common}\n// ---- ${file} ----\ntry {\n${indent(body)}} catch (e) {\n${failure}\n}\n`;
}

const nodes = [];
const idOf = (slug) => 'll_' + slug;

function add(node) { nodes.push(Object.assign({ z: TAB }, node)); return node.id; }

function fn(slug, name, file, { outputs = 1, kind = 'api', x, y, wires }) {
    const text = fnText(file, outputs, kind);
    new Function('msg', 'node', 'flow', 'global', 'env', 'context', text);   // syntax check
    sources[name] = text;
    return add({ id: idOf(slug), type: 'function', name, func: text, outputs, timeout: 0, noerr: 0, initialize: '', finalize: '', libs: [], x, y, wires: wires || Array.from({ length: outputs }, () => []) });
}
const httpIn = (slug, name, method, url, x, y, wires) =>
    add({ id: idOf(slug), type: 'http in', name, url, method, upload: false, swaggerDoc: '', x, y, wires: [wires] });
const httpOut = (slug, x, y) =>
    add({ id: idOf(slug), type: 'http response', name: 'Reply', statusCode: '', headers: {}, x, y, wires: [] });
const comment = (slug, name, info, x, y) => add({ id: idOf(slug), type: 'comment', name, info, x, y, wires: [] });
const mqttIn = (slug, name, topic, x, y, wires) =>
    add({ id: idOf(slug), type: 'mqtt in', name, topic, qos: '1', datatype: 'auto-detect', broker: BROKER_ID, nl: false, rap: true, rh: 0, inputs: 0, x, y, wires: [wires] });
const mqttOut = (slug, name, x, y) =>
    add({ id: idOf(slug), type: 'mqtt out', name, topic: '', qos: '', retain: '', respTopic: '', contentType: '', userProps: '', correl: '', expiry: '', broker: BROKER_ID, x, y, wires: [] });

let y = 40;
const next = (dy = 90) => { const v = y; y += dy; return v; };

// ---- 1. Evaluate readings -------------------------------------------------------------------
comment('c1', '1. Evaluate readings against the limits',
    'Subscribes to the validated readings that the MQTT Validation flow publishes and classifies each one as ok, low or high. ' +
    'Nothing here changes the validation flow or the storage flow. Alerts are published on microhydros/v1/devices/{id}/limits/alert only when a state changes.', 200, next(60));
{
    const row = next();
    mqttIn('in-validated', 'Validated readings', 'microhydros/v1/devices/+/telemetry/validated/+', 170, row, [idOf('evaluate')]);
    fn('evaluate', 'Evaluate against limits', 'evaluate.fn.js', { kind: 'internal', x: 450, y: row, wires: [[idOf('out-alert')]] });
    mqttOut('out-alert', 'Publish limit alert', 740, row);
}

// ---- 2. Limits storage ----------------------------------------------------------------------
comment('c2', '2. Limits storage (retained MQTT message)',
    'The limits of a device live as a retained message on microhydros/v1/devices/{id}/limits/config. This flow subscribes to it, so the ' +
    'limits come back after any restart without changing the Node-RED settings. Publish an empty retained message to clear a profile.', 200, next(60));
{
    const row = next();
    mqttIn('in-config', 'Limits profile (retained)', 'microhydros/v1/devices/+/limits/config', 170, row, [idOf('config-store')]);
    fn('config-store', 'Store profile in memory', 'config-store.fn.js', { outputs: 0, kind: 'internal', x: 450, y: row, wires: [] });
}

// ---- 3. HTTP API ----------------------------------------------------------------------------
comment('c3', '3. HTTP API for the LeafLimits app',
    'Every route needs "Authorization: Bearer <token>" where the token is the tab variable LEAFLIMITS_TOKEN. ' +
    'GET/PUT /leaflimits/api/limits/:device, GET /leaflimits/api/status/:device, POST /leaflimits/api/suggest.', 200, next(60));

function route(slug, title, method, url, handlerFile, handlerName, handlerOutputs) {
    const row = next(handlerOutputs > 1 ? 130 : 90);
    const auth = 'auth-' + slug, handler = 'h-' + slug, reply = 'reply-' + slug;
    httpIn('in-' + slug, title, method, url, 150, row, [idOf(auth)]);
    fn(auth, 'Check token', 'auth.fn.js', { outputs: 2, x: 340, y: row, wires: [[idOf(handler)], [idOf(reply)]] });
    const wires = handlerOutputs === 2 ? [[idOf('out-config')], [idOf(reply)]] : [[idOf(reply)]];
    fn(handler, handlerName, handlerFile, { outputs: handlerOutputs, x: 560, y: row, wires });
    httpOut(reply, 900, row);
    return row;
}
route('get-limits', 'GET limits', 'get', '/leaflimits/api/limits/:device', 'get-limits.fn.js', 'Read profile', 1);
const putRow = route('put-limits', 'PUT limits', 'put', '/leaflimits/api/limits/:device', 'put-limits.fn.js', 'Validate and save profile', 2);
mqttOut('out-config', 'Publish retained limits', 780, putRow + 50);
route('get-status', 'GET status', 'get', '/leaflimits/api/status/:device', 'get-status.fn.js', 'Latest values and state', 1);

{   // suggest: http in -> auth -> prepare -> http request -> parse -> reply, with a catch for network errors
    const row = next(200);
    httpIn('in-suggest', 'POST suggest', 'post', '/leaflimits/api/suggest', 150, row, [idOf('auth-suggest')]);
    fn('auth-suggest', 'Check token', 'auth.fn.js', { outputs: 2, x: 340, y: row, wires: [[idOf('h-suggest')], [idOf('reply-suggest')]] });
    fn('h-suggest', 'Prepare AI request', 'suggest-prepare.fn.js', { outputs: 2, x: 540, y: row, wires: [[idOf('ai-request')], [idOf('reply-suggest')]] });
    add({
        id: idOf('ai-request'), type: 'http request', name: 'Claude API', method: 'use', ret: 'obj', paytoqs: 'ignore', url: '', tls: '',
        persist: false, proxy: '', insecureHTTPParser: false, authType: '', senderr: false, headers: [], x: 740, y: row, wires: [[idOf('parse-suggest')]]
    });
    fn('parse-suggest', 'Clean AI answer', 'suggest-parse.fn.js', { x: 940, y: row, wires: [[idOf('reply-suggest')]] });
    httpOut('reply-suggest', 1140, row);
    add({ id: idOf('catch-ai'), type: 'catch', name: 'AI request failed', scope: [idOf('ai-request')], uncaught: false, x: 540, y: row + 90, wires: [[idOf('err-suggest')]] });
    fn('err-suggest', 'AI unreachable', 'suggest-error.fn.js', { x: 780, y: row + 90, wires: [[idOf('reply-suggest')]] });
}

// ---- 4. App files ---------------------------------------------------------------------------
comment('c4', '4. The LeafLimits web app',
    'Serves the built Angular app from the folder in LEAFLIMITS_APP_DIR (default /data/leaflimits-app) at /leaflimits/. ' +
    'Copy the files there with: docker cp app-dist/. <node-red container>:/data/leaflimits-app/', 200, next(150));
{
    const row = next(170);
    httpIn('in-app', 'GET app', 'get', '/leaflimits', 150, row, [idOf('static-request')]);
    httpIn('in-app-file', 'GET app file', 'get', '/leaflimits/:file', 150, row + 60, [idOf('static-request')]);
    fn('static-request', 'Pick file', 'static-request.fn.js', { outputs: 2, x: 380, y: row + 30, wires: [[idOf('file-in')], [idOf('reply-app')]] });
    add({ id: idOf('file-in'), type: 'file in', name: 'Read file', filename: 'filename', filenameType: 'msg', format: '', chunk: false, sendError: false, encoding: 'none', allProps: false, x: 590, y: row + 30, wires: [[idOf('static-response')]] });
    fn('static-response', 'Set headers', 'static-response.fn.js', { x: 790, y: row + 30, wires: [[idOf('reply-app')]] });
    httpOut('reply-app', 1000, row + 30);
    add({ id: idOf('catch-file'), type: 'catch', name: 'File missing', scope: [idOf('file-in')], uncaught: false, x: 590, y: row + 110, wires: [[idOf('missing')]] });
    fn('missing', 'Not found', 'static-missing.fn.js', { x: 790, y: row + 110, wires: [[idOf('reply-app')]] });
}

const tab = {
    id: TAB, type: 'tab', label: 'LeafLimits', disabled: true,
    info: 'Plant-specific limits for MicroHydros. Additive: it only reads validated readings and never changes the validation or storage flows.\n\n' +
        'The tab is imported DISABLED. Before enabling it, set the credential variables (Edit tab, Environment Variables): LEAFLIMITS_TOKEN and ANTHROPIC_API_KEY.\n' +
        'Disable the tab again to return to the original behaviour.',
    env: [
        { name: 'LEAFLIMITS_TOKEN', value: '', type: 'cred' },
        { name: 'ANTHROPIC_API_KEY', value: '', type: 'cred' },
        { name: 'ANTHROPIC_MODEL', value: 'claude-sonnet-5', type: 'str' },
        { name: 'ANTHROPIC_API_URL', value: 'https://api.anthropic.com/v1/messages', type: 'str' },
        { name: 'SUGGEST_MAX_PER_HOUR', value: '20', type: 'num' },
        { name: 'LEAFLIMITS_APP_DIR', value: '/data/leaflimits-app', type: 'str' }
    ]
};
const flows = [tab, ...nodes.map((n) => { const { z, ...rest } = n; return Object.assign({ z }, rest); })];

// Sanity checks: unique ids, every wire and scope target exists.
const ids = new Set();
for (const n of flows) { if (ids.has(n.id)) throw new Error('duplicate id ' + n.id); ids.add(n.id); }
for (const n of flows) {
    for (const group of n.wires || []) for (const t of group) if (!ids.has(t)) throw new Error(n.id + ' wired to missing ' + t);
    for (const t of n.scope || []) if (!ids.has(t)) throw new Error(n.id + ' scope has missing ' + t);
}

module.exports = { flows, sources, BROKER_ID, TAB };

if (require.main === module) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, JSON.stringify(flows, null, 4) + '\n');
    const counts = {};
    for (const n of flows) counts[n.type] = (counts[n.type] || 0) + 1;
    console.log('wrote ' + path.relative(process.cwd(), OUT) + ': ' + flows.length + ' nodes', JSON.stringify(counts));
}
